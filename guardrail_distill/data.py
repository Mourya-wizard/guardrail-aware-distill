import guardrail_distill.env as env  # noqa
import argparse
import json
import os
from collections import Counter


def get_domain(phase="phase2"):
    if env.PHASES[phase] == "rental_support_v1":
        from .domains.rental_support_v1 import RentalSupportV1
        return RentalSupportV1()
    from .domains.rental_support import RentalSupport
    return RentalSupport()


def build(phase, seed=0):
    out = env.paths(phase)["data"]
    os.makedirs(out, exist_ok=True)
    d = get_domain(phase).generate_data(seed)
    for s, rows in d.items():
        with open(f"{out}/{s}.jsonl", "w", encoding="utf-8") as f:
            f.writelines(json.dumps(r) + "\n" for r in rows)
    return d


def load(phase, split):
    return [json.loads(l) for l in open(f"{env.paths(phase)['data']}/{split}.jsonl", encoding="utf-8")]


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Generate the templated dataset for a phase.")
    ap.add_argument("--phase", default="phase2", choices=list(env.PHASES))
    a = ap.parse_args()
    if a.phase == "phase1" and os.path.exists(f"{env.paths('phase1')['data']}/test.jsonl"):
        print("phase1 data is committed in data/phase1 (generated by the tag track-a-v1 code); not regenerating.")
    else:
        d = build(a.phase)
        for s, rows in d.items():
            print(s, len(rows), dict(Counter(r["cls"] for r in rows)), "templates:", len({r["template_id"] for r in rows}))
