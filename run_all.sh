#!/usr/bin/env bash
# Reproduce the experiments. Usage: bash run_all.sh [--phase1] [--phase2] [--dry-run]   (default: both phases)
set -euo pipefail
cd "$(dirname "$0")"
DRY=0; P1=0; P2=0
for a in "$@"; do
  case "$a" in --dry-run) DRY=1 ;; --phase1) P1=1 ;; --phase2) P2=1 ;; *) echo "unknown arg $a"; exit 1 ;; esac
done
if [ "$P1" = 0 ] && [ "$P2" = 0 ]; then P1=1; P2=1; fi
export HF_HOME="$PWD/.cache/huggingface" TORCH_HOME="$PWD/.cache/torch" XDG_CACHE_HOME="$PWD/.cache" MPLCONFIGDIR="$PWD/.cache/mpl" WANDB_DISABLED=true PIP_REQUIRE_VIRTUALENV=1
venv_bins() { if [ -d .venv/Scripts ]; then PY=.venv/Scripts/python.exe; PIP=.venv/Scripts/pip.exe; else PY=.venv/bin/python; PIP=.venv/bin/pip; fi; }
venv_bins
run() { echo "+ $*"; if [ "$DRY" = 0 ]; then "$@"; fi; }

if [ ! -d .venv ]; then
  echo "+ create .venv and install requirements.txt (torch from the cu128 index)"
  if [ "$DRY" = 0 ]; then
    (python3 -m venv .venv 2>/dev/null || py -3 -m venv .venv); venv_bins
    $PIP install --extra-index-url https://download.pytorch.org/whl/cu128 -r requirements.txt
  fi
fi
M="-m guardrail_distill"
run $PY -m pytest tests -q

if [ "$P1" = 1 ]; then
  echo "== Phase 1 (data/phase1 is committed; it was generated by the code at tag track-a-v1)"
  for c in student_none student_prompt teacher_prompt; do run $PY $M.evaluation --phase phase1 --cond $c --n_latency 20; done
  run $PY $M.context_distill --phase phase1 --run opcd    --guided_frac 0.0 --steps 150 --eval_every 25
  run $PY $M.context_distill --phase phase1 --run opcd_gr --guided_frac 0.3 --steps 150 --eval_every 25
  run $PY $M.dpo_baseline --phase phase1 --run dpo
  for c in opcd opcd_gr dpo; do run $PY $M.evaluation --phase phase1 --cond $c --n_latency 20; done
  run $PY $M.evaluation --phase phase1 --cond summary
  run $PY $M.significance --phase phase1
  run $PY $M.plots --phase phase1
fi

if [ "$P2" = 1 ]; then
  echo "== Phase 2: data, then every training / evaluation / audit job through the GPU queue (64 GB GPU memory, 19 CPU threads)"
  run $PY $M.data --phase phase2
  run $PY scripts/phase2_jobs.py
  run $PY scripts/job_queue.py --jobs results/phase2/raw/queue/jobs.json --mem_gb 64 --threads 19
  run $PY $M.evaluation --phase phase2 --cond summary
  run $PY $M.significance --phase phase2
  run $PY $M.plots --phase phase2
fi
